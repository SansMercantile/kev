#!/usr/bin/env python3
"""
Generate ``src/xr/data/schoolCampus.ts`` from the backend campus model.

The repo already had one hand-maintained mirror (``campusFloors.ts``, which
self-documents as "MIRROR of backend FLOORS — update together"). Hand mirrors
drift, so this one is generated: run it after changing
``backend/core/school_campus.py`` or adding tutor agents under
``multi_agents/``.

    python3 scripts/generate_campus_mirror.py            # from repo root or kev/
    python3 scripts/generate_campus_mirror.py --check    # CI: fail if stale

The mirror is deliberately *compact* — it carries everything the 3D campus
needs to render offline (floors, hallway, rooms, subject wings, specializations,
virtual-school levels, lead tutor per class) but not all 872 registry
``tutor_id``s. Those stay in ``GET /xr/campus/subject-wings``.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from typing import Any, Dict, List

HERE = os.path.dirname(os.path.abspath(__file__))
KEV_ROOT = os.path.dirname(HERE)
REPO_ROOT = os.path.dirname(KEV_ROOT)
OUT_PATH = os.path.join(KEV_ROOT, "src", "xr", "data", "schoolCampus.ts")

HEADER = '''// GENERATED FILE — do not edit by hand.
//
//   python3 scripts/generate_campus_mirror.py
//
// Source of truth: kev/backend/core/school_campus.py (which composes
// backend/core/campus_floors.py, virtual_school/core/virtual_school_building.py
// and the real multi_agents/ tutor catalog via services/agent_catalog.py).
//
// Offline mirror of GET /xr/campus/school, compacted: it carries everything the
// 3D campus needs to render with zero connectivity — all {floor_count} floors
// (including floor 0, the Grand Concourse Hallway), all {room_count} rooms, the
// {subject_count} subject wings with their {class_count} classes, and the
// virtual-school building's {vs_count} facilities across its six levels.
//
// The full 872 registry tutor_ids per class are served by
// GET /xr/campus/subject-wings; each class here keeps its lead tutor per role.
//
// campusFloors.ts (the original 4-floor mirror) is intentionally left in place
// and still used as the last-resort fallback for legacy code paths.

'''


def _js(value: Any) -> str:
    """
    Emit JSON (which is valid TS for plain data) as compactly as possible.

    This is a generated blob, not hand-read source: minifying it roughly halves
    the file, which matters because it ships in the PWA precache.
    """
    return json.dumps(value, ensure_ascii=False, sort_keys=False, separators=(",", ":"))


def compact_class(klass: Dict[str, Any]) -> Dict[str, Any]:
    tutors = klass.get("tutors") or {}
    return {
        "id": klass["id"],
        "specialization": klass["specialization"],
        "level": klass["level"],
        "subject": klass["subject"],
        "floor": klass["floor"],
        "agentCount": klass.get("agentCount", 0),
        "leadTutors": {role: ids[0] for role, ids in tutors.items() if ids},
    }


#: Fields a class room can live without, because the renderer derives them from
#: ``subject`` + ``level`` + ``specialization`` (see ``describeRoom()`` in the
#: campus module). Hand-authored rooms keep all of them.
DERIVABLE_ROOM_FIELDS = ("description", "wing", "levelLabel", "subjectDisplayName")


def compact_facility(fac: Dict[str, Any], *, slim: bool = False) -> Dict[str, Any]:
    """Keep render-relevant fields; drop derivable prose from the 176 class rooms."""
    out = {
        "id": fac["id"],
        "roomNumber": fac.get("roomNumber", ""),
        "name": fac.get("name", ""),
        "type": fac.get("type", "classroom"),
        "description": fac.get("description", ""),
        "interactActionLabel": fac.get("interactActionLabel", "Enter"),
        "coordinates": fac.get("coordinates", {"x": 0, "z": 0}),
    }
    for key in (
        "classId", "subject", "subjectDisplayName", "level", "levelLabel", "wing",
        "color", "associatedLabId", "tutorInResidence", "leadRegistryTutor",
        "agentCount", "isHallway", "capacity", "dimensions", "equipment",
        "virtualTools", "accessibilityFeatures", "isBooked", "subjectArea",
        "schoolFacilityType", "levelDisplayName", "sourceFacilityId",
    ):
        if key in fac and fac[key] is not None:
            if slim and key in DERIVABLE_ROOM_FIELDS:
                continue
            out[key] = fac[key]
    if slim:
        # ``description`` is regenerated by describeRoom() from the parts above.
        out.pop("description", None)
        out["slim"] = True
    # 3D coordinates for virtual-school rooms are [x, y, z]; normalise to {x,z}
    # plus a y so one renderer can place both campuses.
    coords = fac.get("coordinates")
    if isinstance(coords, dict) and "y" in coords:
        out["coordinates"] = {"x": coords.get("x", 0), "y": coords.get("y", 0), "z": coords.get("z", 0)}
    return out


def compact_floor(floor: Dict[str, Any]) -> Dict[str, Any]:
    out = {
        "floorNumber": floor["floorNumber"],
        "name": floor["name"],
        "subtitle": floor.get("subtitle", ""),
        "color": floor.get("color", "#06b6d4"),
        "kind": floor.get("kind", "subject_wing"),
        "facilities": [
            compact_facility(f, slim=floor.get("kind") == "subject_wing" or bool(f.get("classId")))
            for f in floor.get("facilities", [])
        ],
    }
    for key in ("isHallway", "subjectAreas", "corridor", "bannerSubjects", "annex"):
        if key in floor:
            out[key] = floor[key]
    return out


ACCESSORS_TEMPLATE = """
// --- Convenience accessors (kept tiny; the 3D campus and tour use these) ---

export const HALLWAY_FLOOR = SCHOOL_CAMPUS.hallwayFloor;

export const CAMPUS_FLOORS = SCHOOL_CAMPUS.floors as unknown as SchoolFloor[];

export const SUBJECT_WINGS = SCHOOL_CAMPUS.subjectWings as unknown as SubjectWing[];

export const VIRTUAL_SCHOOL = SCHOOL_CAMPUS.virtualSchool as unknown as VirtualSchool;

export const CAMPUS_STATISTICS = SCHOOL_CAMPUS.statistics;

/** Corridor geometry the 3D renderer lays rooms out with. */
export const CORRIDOR = SCHOOL_CAMPUS.corridor;

/** The five agent roles every class ships with. */
export const TUTOR_ROLES = SCHOOL_CAMPUS.tutorRoles;

export function floorByNumber(n: number): SchoolFloor | undefined {
  return CAMPUS_FLOORS.find((f) => f.floorNumber === n);
}

/** Floor 0 — the Grand Concourse Hallway every other floor hangs off. */
export function hallway(): SchoolFloor | undefined {
  return floorByNumber(HALLWAY_FLOOR);
}

export function wingBySubject(subject: string): SubjectWing | undefined {
  const key = subject.trim().toLowerCase().replace(/ /g, '_');
  return SUBJECT_WINGS.find((w) => w.subject.toLowerCase() === key || w.id === key);
}

export function classById(id: string): SubjectClass | undefined {
  for (const w of SUBJECT_WINGS) {
    const hit = w.classes.find((c) => c.id === id);
    if (hit) return hit;
  }
  return undefined;
}

/** Education-level label for a level token: high_school -> High School (9-12). */
export function levelLabel(level: string): string {
  return (SCHOOL_CAMPUS.levelLabels as Record<string, string>)[level] ?? level;
}

/** Every room in the school, flattened (hallway + legacy wings + subject floors). */
export function allRooms(): SchoolFacility[] {
  return CAMPUS_FLOORS.flatMap((f) => f.facilities);
}

/** Rooms on one floor. */
export function roomsOnFloor(n: number): SchoolFacility[] {
  return floorByNumber(n)?.facilities ?? [];
}

/** All classes across every subject area. */
export function allClasses(): SubjectClass[] {
  return SUBJECT_WINGS.flatMap((w) => w.classes);
}

/**
 * Human description for any room.
 *
 * Class rooms ship without prose (they are flagged `slim`) to keep this mirror
 * small, so their description is composed here from subject + level + name;
 * the hand-authored hallway, legacy and virtual-school rooms carry their own.
 */
export function describeRoom(room: SchoolFacility): string {
  if (!room.slim && room.description) return room.description;
  const wing = wingBySubject(room.subject ?? '');
  const subjectName = room.subjectDisplayName ?? wing?.displayName ?? room.subject ?? 'KEV';
  const level = room.level ? levelLabel(room.level) : '';
  const agents = room.agentCount
    ? ` ${room.agentCount} specialized agents (tutor, expert, teacher, invigilator, mentor).`
    : '';
  return `${subjectName} — ${room.name}${level ? ` — ${level}` : ''}.${agents}`;
}

/** Subject banners shown along the hallway: one per subject area. */
export function hallwayBanners(): HallwayBanner[] {
  return hallway()?.bannerSubjects ?? [];
}
"""


def build_mirror(campus: Dict[str, Any]) -> str:
    stats = campus["statistics"]
    floors = [compact_floor(f) for f in campus["floors"]]

    wings = []
    for wing in campus["subjectWings"]:
        wings.append(
            {
                "id": wing["id"],
                "subject": wing["subject"],
                "displayName": wing["displayName"],
                "floor": wing["floor"],
                "wing": wing["wing"],
                "color": wing["color"],
                "icon": wing["icon"],
                "labId": wing["labId"],
                "blurb": wing["blurb"],
                "levels": wing["levels"],
                "specializations": wing["specializations"],
                "specializationCount": wing["specializationCount"],
                "classCount": wing["classCount"],
                "agentCount": wing["agentCount"],
                "classes": [compact_class(c) for c in wing["classes"]],
            }
        )

    vs = campus.get("virtualSchool") or {}
    vs_levels = []
    for level in vs.get("levels", []):
        vs_levels.append(
            {
                "level": level["level"],
                "levelDisplayName": level["levelDisplayName"],
                "order": level["order"],
                "color": level["color"],
                "themeAndSubject": level["themeAndSubject"],
                "facilitiesCount": level["facilitiesCount"],
                "facilities": [compact_facility(f) for f in level["facilities"]],
            }
        )

    payload = {
        "hallwayFloor": campus["hallwayFloor"],
        "corridor": campus["corridor"],
        "tutorRoles": campus["tutorRoles"],
        "levelOrder": campus["levelOrder"],
        "levelLabels": campus["levelLabels"],
        "statistics": stats,
        "floors": floors,
        "subjectWings": wings,
        "virtualSchool": {
            "available": vs.get("available", False),
            "building": vs.get("building"),
            "statistics": vs.get("statistics", {}),
            "levels": vs_levels,
        },
    }

    header = HEADER.format(
        floor_count=len(floors),
        room_count=stats["totalRooms"],
        subject_count=stats["subjectAreas"],
        class_count=stats["classes"],
        vs_count=stats["virtualSchoolFacilities"],
    )

    body = [
        "// eslint-disable-next-line @typescript-eslint/no-explicit-any",
        f"export const SCHOOL_CAMPUS = {_js(payload)} as const;",
        "",
        ACCESSORS_TEMPLATE,
    ]

    types = '''
// --- Types (structurally compatible with CampusFloor/CampusFacility in ../../types) ---

export type SchoolRoomType =
  | 'lab' | 'auditorium' | 'lounge' | 'faculty_office' | 'observatory' | 'cleanroom'
  | 'gallery' | 'reception' | 'courtyard' | 'hallway' | 'kiosk' | 'portal' | 'elevator'
  | 'classroom' | 'seminar_room' | 'lecture_hall' | 'library' | 'gymnasium' | 'music_room'
  | 'art_studio' | 'computer_lab' | 'cafeteria' | 'studio' | 'workshop';

export interface SchoolFacility {
  id: string;
  roomNumber: string;
  name: string;
  type: SchoolRoomType | string;
  description: string;
  interactActionLabel: string;
  coordinates: { x: number; y?: number; z: number };
  classId?: string;
  subject?: string;
  subjectDisplayName?: string;
  level?: string;
  levelLabel?: string;
  /** True when derivable prose was stripped to keep this mirror small. */
  slim?: boolean;
  wing?: string;
  color?: string;
  associatedLabId?: string | null;
  tutorInResidence?: string | null;
  leadRegistryTutor?: string | null;
  agentCount?: number;
  capacity?: number | null;
  dimensions?: number[] | null;
  equipment?: string[];
  virtualTools?: string[];
  accessibilityFeatures?: string[];
  isBooked?: boolean;
  subjectArea?: string | null;
  schoolFacilityType?: string;
  levelDisplayName?: string;
  sourceFacilityId?: string;
}

export interface HallwayBanner {
  subject: string;
  displayName: string;
  color: string;
  icon: string;
  floor: number;
  specializationCount: number;
  classCount: number;
  agentCount: number;
  blurb: string;
}

export interface SchoolFloor {
  floorNumber: number;
  name: string;
  subtitle: string;
  color: string;
  kind: 'hallway' | 'legacy_xr_wing' | 'subject_wing' | string;
  facilities: SchoolFacility[];
  isHallway?: boolean;
  subjectAreas?: string[];
  corridor?: { length: number; halfWidth: number; roomRowX: number; pitchZ: number };
  bannerSubjects?: HallwayBanner[];
  annex?: { classCount: number; subjects: string[]; note: string };
}

export interface SubjectLevelGroup {
  level: string;
  label: string;
  specializations: string[];
  count: number;
}

export interface SubjectClass {
  id: string;
  specialization: string;
  level: string;
  subject: string;
  floor: number;
  agentCount: number;
  leadTutors: Record<string, string>;
}

export interface SubjectWing {
  id: string;
  subject: string;
  displayName: string;
  floor: number;
  wing: string;
  color: string;
  icon: string;
  labId: string | null;
  blurb: string;
  levels: SubjectLevelGroup[];
  specializations: string[];
  specializationCount: number;
  classCount: number;
  agentCount: number;
  classes: SubjectClass[];
}

export interface VirtualSchoolLevel {
  level: string;
  levelDisplayName: string;
  order: number;
  color: string;
  themeAndSubject: string;
  facilitiesCount: number;
  facilities: SchoolFacility[];
}

export interface VirtualSchool {
  available: boolean;
  building: {
    name: string;
    address: string;
    totalFacilities: number;
    layout: Record<string, unknown>;
  } | null;
  statistics: Record<string, unknown>;
  levels: VirtualSchoolLevel[];
}
'''

    return header + types.strip() + "\n\n" + "\n".join(body)


def load_campus() -> Dict[str, Any]:
    """Import the backend model directly (no HTTP, no FastAPI needed)."""
    if REPO_ROOT not in sys.path:
        sys.path.insert(0, REPO_ROOT)
    from kev.backend.core.school_campus import build_school_campus  # type: ignore

    return build_school_campus(force=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed mirror differs from a fresh generation")
    parser.add_argument("--out", default=OUT_PATH, help="output path")
    args = parser.parse_args()

    campus = load_campus()
    generated = build_mirror(campus)

    if args.check:
        if not os.path.exists(args.out):
            print(f"FAIL: {os.path.relpath(args.out, REPO_ROOT)} does not exist — run "
                  f"`python3 scripts/generate_campus_mirror.py`")
            return 1
        existing = open(args.out, encoding="utf-8").read()
        if existing != generated:
            print(f"FAIL: {os.path.relpath(args.out, REPO_ROOT)} is stale.")
            print("      The backend campus model changed. Re-run:")
            print("        python3 scripts/generate_campus_mirror.py")
            return 1
        print(f"OK: {os.path.relpath(args.out, REPO_ROOT)} is in sync with the backend campus model.")
        return 0

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(generated)

    stats = campus["statistics"]
    print(f"Wrote {os.path.relpath(args.out, REPO_ROOT)}")
    print(f"  floors            : {len(campus['floors'])} (0-{max(f['floorNumber'] for f in campus['floors'])})")
    print(f"  rooms total       : {stats['totalRooms']}")
    print(f"  hallway facilities: {stats['hallwayFacilities']}")
    print(f"  legacy originals  : {stats['legacyOriginalFacilities']} (+{stats['annexRooms']} annexes)")
    print(f"  subject rooms     : {stats['subjectRooms']}")
    print(f"  subject areas     : {stats['subjectAreas']}")
    print(f"  specializations   : {stats['specializations']}")
    print(f"  classes           : {stats['classes']}")
    print(f"  tutor agents      : {stats['tutorAgents']}")
    print(f"  virtual school    : {stats['virtualSchoolFacilities']} facilities / "
          f"{len(campus['virtualSchool']['levels'])} levels")
    print(f"  size              : {len(generated) / 1024:.1f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
