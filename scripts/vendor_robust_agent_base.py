"""
Vendors ROBUST_AGENT_BASE.py into kev/multi_agents/robust_agent_base.py so it's
importable as `kev.multi_agents.robust_agent_base` from any deployment
(container, AWS, etc.) without depending on a sibling `shared_resources`
checkout being present at a specific relative path.

Also adds a stateless `invoke()` entry point: the original RobustAgent is
designed as a long-running, queue-processing worker (start()/stop(), a
background asyncio loop, a 30s heartbeat task). That model doesn't fit a
stateless server where an agent is instantiated fresh per request and may
run on any replica. `invoke()` calls handle_message() directly -- no
background tasks, no shared state -- and captures whatever the agent would
have sent via send_message() so the caller gets a normal return value.
"""
