DST = Path(r"C:\Users\kpasc\source\repos\constellation\kev\multi_agents\robust_agent_base.py")

STATELESS_ADDITION = '''
    # ------------------------------------------------------------------
    # Stateless invocation (added for KEV's stateless-server deployment).
    # The methods above (start/stop/_process_messages/_heartbeat_monitor)
    # assume a long-lived worker process. invoke() bypasses all of that:
    # it runs handle_message() once, directly, with no background tasks,
    # so a fresh agent instance can be created per request on any replica
    # and safely discarded afterwards.
    # ------------------------------------------------------------------
    async def invoke(
        self,
        message_type: "MessageType",
        payload: Dict[str, Any],
        sender_id: str = "api",
    ) -> Dict[str, Any]:
        """Process a single message statelessly and return the result.

        No background loop, no heartbeat, no persistent queue -- safe to
        call on a fresh instance on any server/replica/lambda invocation.
        """
        self._captured_responses: List[Dict[str, Any]] = []
        was_running = self.is_running
        self.is_running = True  # allow send_message()/_deliver_locally() to work
        message = AgentMessage(
            sender_id=sender_id,
            sender_type=self.agent_type,
            recipient_id=self.agent_id,
            message_type=message_type,
            payload=payload,
            timestamp=datetime.utcnow(),
        )
        try:
            await self.handle_message(message)
            return {
                "agent_id": self.agent_id,
                "status": "success",
                "responses": self._captured_responses,
            }
        except Exception as exc:  # noqa: BLE001
            logger.error(f"Agent {self.agent_id} invoke() failed: {exc}", exc_info=True)
            return {
                "agent_id": self.agent_id,
                "status": "error",
                "error": str(exc),
            }
        finally:
            self.is_running = was_running

    async def _deliver_locally(self, message: "AgentMessage"):
        """Capture messages sent during invoke() instead of dropping them."""
        if not hasattr(self, "_captured_responses"):
            self._captured_responses = []
        self._captured_responses.append({
            "recipient_id": message.recipient_id,
            "message_type": message.message_type.value,
            "payload": message.payload,
        })

'''

def main():
    if not SRC.exists():
        raise SystemExit(f"Source file not found: {SRC}")

    text = SRC.read_text(encoding="utf-8")

    marker = "    def get_status(self) -> Dict[str, Any]:"
    if marker not in text:
        raise SystemExit("Could not find insertion point (get_status) in source file")

